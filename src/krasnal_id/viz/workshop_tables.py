"""Numbers and tables for the CVWW manuscript, generated from result artifacts.

The workshop paper quotes dozens of statue-level intervals. Typing them would
re-open the failure §6.4 exists to prevent -- a published number with no artifact
behind it -- so the manuscript cites them by metric name instead:

    \\wv{dinov2_top_1}      the point estimate, in the paper's units
    \\wvci{dinov2_top_1}    its 95% statue-bootstrap interval, "lower to upper"

and this module writes the macro file those commands read, plus the generated
tables. A name absent from the artifact renders as a red MISSING, which the
build check searches for, rather than as a stale or invented number.

Units: proportions are reported in percentage points; slopes are already in
points per doubling; counts and p-values are written as they are.
"""

import json
import re
from collections.abc import Mapping
from pathlib import Path

from krasnal_id.atomic import atomic_text


class WorkshopTableError(ValueError):
    """Raised when an artifact the manuscript depends on is missing or malformed."""


# Metrics already in accuracy points rather than proportions.
_POINTS = re.compile(r"points_per_doubling$")
# Metrics that are counts or p-values, written verbatim.
_RAW = re.compile(r"(_wins|_losses|_p_value|_queries|_statues|_count|_errors|_permutations)$")
# AUROCs and their differences are probabilities the paper prints as 0.896, not 89.6.
_AUROC = re.compile(r"_auroc$")
# Selected weights are printed as chosen, never as percentages.
_WEIGHT = re.compile(r"_weight$")


def load_metrics(path: Path) -> dict[str, dict[str, float | None]]:
    """Read every metric of one artifact, keyed by name."""
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        return {
            str(m["name"]): {
                "value": float(m["value"]),
                "lower": None if m.get("lower_bound") is None else float(m["lower_bound"]),
                "upper": None if m.get("upper_bound") is None else float(m["upper_bound"]),
            }
            for m in payload["metrics"]
        }
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise WorkshopTableError(f"cannot read result artifact {path}: {error}") from error


def scale(name: str, value: float) -> float:
    """Convert a stored metric into the unit the manuscript prints."""
    if _RAW.search(name) or _POINTS.search(name) or _AUROC.search(name) or _WEIGHT.search(name):
        return value
    return value * 100.0


def formatted(name: str, value: float) -> str:
    """Format one number for the page."""
    if name.endswith("_p_value"):
        if value >= 0.001:
            return f"{value:.2g}"
        mantissa, exponent = f"{value:.1e}".split("e")
        return f"${mantissa}\\times10^{{{int(exponent)}}}$"
    if _RAW.search(name):
        return f"{value:.0f}"
    if _WEIGHT.search(name):
        return f"{value:g}"
    scaled = scale(name, value)
    if _AUROC.search(name):
        text = f"{scaled:.3f}"
        return text.replace("-", "$-$") if scaled < 0 else text
    # Typeset a real minus sign rather than a hyphen.
    text = f"{scaled:.1f}"
    # Never a signed zero: "-0.0" reads as a negative effect that rounding erased.
    if text == "-0.0":
        return "0.0"
    return text.replace("-", "$-$") if scaled < 0 else text


def macro_file(
    metrics: Mapping[str, Mapping[str, float | None]], *, with_commands: bool = True
) -> str:
    """The `\\wv`/`\\wvci` definitions for every metric, as LaTeX source.

    `with_commands=False` writes only the values, for a second file read after
    `numbers.tex` has defined the commands (the family study's numbers).
    """
    header = [
        "% Generated by `krasnal-id visualize workshop-tables`. Do not edit by hand.",
        r"\makeatletter",
    ]
    commands = [
        r"\newcommand{\wv}[1]{\@ifundefined{wv@#1@v}"
        r"{\textbf{\color{red}MISSING:\detokenize{#1}}}{\csname wv@#1@v\endcsname}}",
        r"\newcommand{\wvci}[1]{\@ifundefined{wv@#1@ci}"
        r"{\textbf{\color{red}MISSING:\detokenize{#1}}}{\csname wv@#1@ci\endcsname}}",
        # One end of an interval, for a sentence that bounds an effect from one side.
        r"\newcommand{\wvlo}[1]{\@ifundefined{wv@#1@lo}"
        r"{\textbf{\color{red}MISSING:\detokenize{#1}}}{\csname wv@#1@lo\endcsname}}",
        r"\newcommand{\wvhi}[1]{\@ifundefined{wv@#1@hi}"
        r"{\textbf{\color{red}MISSING:\detokenize{#1}}}{\csname wv@#1@hi\endcsname}}",
    ]
    lines = header + (commands if with_commands else [])
    for name in sorted(metrics):
        metric = metrics[name]
        value = metric["value"]
        assert value is not None
        lines.append(rf"\@namedef{{wv@{name}@v}}{{{formatted(name, value)}}}")
        lower, upper = metric["lower"], metric["upper"]
        if lower is not None and upper is not None:
            lines.append(
                # "to", not an en dash: between two negative numbers a dash reads
                # as a minus sign, and "-1.5--0.3" rendered as one ambiguous run.
                rf"\@namedef{{wv@{name}@ci}}"
                rf"{{{formatted(name, lower)} to {formatted(name, upper)}}}"
            )
            lines.append(rf"\@namedef{{wv@{name}@lo}}{{{formatted(name, lower)}}}")
            lines.append(rf"\@namedef{{wv@{name}@hi}}{{{formatted(name, upper)}}}")
    lines.append(r"\makeatother")
    return "\n".join(lines) + "\n"


_MATCHER_NAMES = {"sift": "SIFT", "disk-lightglue": "DISK+LightGlue", "loftr": "LoFTR"}


def fold_weight_table(path: Path) -> str:
    """The weight each matcher chose on each statue fold, as a LaTeX table body."""
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))["fold_weights"]
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise WorkshopTableError(f"cannot read fold weights from {path}: {error}") from error
    if not rows:
        raise WorkshopTableError(f"{path} records no fold weights; was rerank part run?")
    body = [
        r"\begin{tabular}{@{}lccccc@{}}",
        r"\toprule",
        r"Matcher & Fold & Weight & Selection top-1 & Held-out queries & statues \\",
        r"\midrule",
    ]
    previous = None
    for row in rows:
        # The paper's name for the matcher, once per group, with a rule between groups.
        name = _MATCHER_NAMES.get(row["matcher"], row["matcher"])
        if previous is not None and row["matcher"] != previous:
            body.append(r"\midrule")
        shown = name if row["matcher"] != previous else ""
        previous = row["matcher"]
        body.append(
            f"{shown} & {row['fold']} & {row['weight']:g} & "
            f"{100 * row['selection_top_1']:.1f} & {row['held_out_queries']} & "
            f"{row['held_out_statues']} \\\\"
        )
    body += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(body) + "\n"


# Backbones and matchers as the paper names them, in the order its tables use.
_BACKBONES = (("dinov2", "DINOv2"), ("clip", "CLIP"), ("dinov3", "DINOv3"), ("siglip2", "SigLIP~2"))
_NULL_CHECKPOINTS = (
    ("dinov2-large", "ViT-L/14"),
    ("dinov2-registers", "ViT-B/14 + registers"),
    ("dinov2-registers-large", "ViT-L/14 + registers"),
)


def _cell(metrics: Mapping[str, Mapping[str, float | None]], name: str) -> str:
    """One table cell: the value, and its interval when it has one."""
    metric = metrics[name]
    value = metric["value"]
    assert value is not None
    text = formatted(name, value)
    lower, upper = metric["lower"], metric["upper"]
    if lower is not None and upper is not None:
        text += f" [{formatted(name, lower)}, {formatted(name, upper)}]"
    return text


def _table(columns: str, header: str, rows: list[str]) -> str:
    lines = [
        rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
        r"\toprule",
        header,
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def reviewer_tables(metrics: Mapping[str, Mapping[str, float | None]]) -> dict[str, str]:
    """The section 7.15-7.16 supplement tables, each built only if its metrics exist.

    A table whose metrics the artifact does not carry is left out rather than
    filled with MISSING, because a run without that part is a legitimate run; the
    manuscript's \\input then fails visibly, which is the check that matters.
    """
    tables: dict[str, str] = {}
    present = [(key, label) for key, label in _BACKBONES if f"{key}_reject_cosine_auroc" in metrics]
    if present:
        rows = []
        for key, label in present:
            cells = [label]
            for signal in ("cosine", "margin", "knn"):
                cells.append(_cell(metrics, f"{key}_reject_{signal}_auroc"))
                cells.append(
                    formatted(
                        f"{key}_reject_{signal}_false_acceptance_90",
                        metrics[f"{key}_reject_{signal}_false_acceptance_90"]["value"] or 0.0,
                    )
                )
            rows.append(" & ".join(cells) + r" \\")
        tables["reviewer-rejection.tex"] = _table(
            "lcccccc",
            r"& \multicolumn{2}{c}{Cosine} & \multicolumn{2}{c}{Margin}"
            r" & \multicolumn{2}{c}{$k$-NN} \\"
            "\n"
            r"Backbone & AUROC & FA@90 & AUROC & FA@90 & AUROC & FA@90 \\",
            rows,
        )
    sizes = sorted(
        {
            int(n.split("_pool_")[1].split("_")[0])
            for n in metrics
            if "_geo_minus_random_pool_" in n and "_noise_" in n
        }
    )
    radii = sorted(
        {
            float(n.rsplit("_noise_", 1)[1])
            for n in metrics
            if "_noise_" in n and n.startswith("dinov2_")
        }
    )
    # The full located set is the same pool for both arms, so its difference is
    # identically zero; a row of zeros would read as a measurement.
    sizes = [
        size
        for size in sizes
        if any(
            v != 0.0
            for v in metrics[f"dinov2_geo_minus_random_pool_{size}"].values()
            if v is not None
        )
    ]
    if sizes and radii:
        rows = []
        for size in sizes:
            cells = [str(size), _cell(metrics, f"dinov2_geo_minus_random_pool_{size}")]
            cells += [
                _cell(metrics, f"dinov2_geo_minus_random_pool_{size}_noise_{r:g}") for r in radii
            ]
            rows.append(" & ".join(cells) + r" \\")
        tables["reviewer-noise.tex"] = _table(
            "l" + "c" * (len(radii) + 1),
            "Pool & As placed & " + " & ".join(f"{r:g}\\,m" for r in radii) + r" \\",
            rows,
        )
    perm_sizes = sorted(
        {int(n.split("_pool_")[1].split("_")[0]) for n in metrics if "_geo_permutation_pool_" in n}
    )
    if perm_sizes:
        rows = []
        for key, label in _BACKBONES:
            if f"{key}_geo_permutation_mean_p_value" not in metrics:
                continue
            cells = [label]
            for size in perm_sizes:
                cells.append(_cell(metrics, f"{key}_geo_minus_random_pool_{size}"))
                cells.append(_cell(metrics, f"{key}_geo_permutation_pool_{size}_null_mean"))
            cells.append(
                formatted(
                    f"{key}_geo_permutation_mean_p_value",
                    metrics[f"{key}_geo_permutation_mean_p_value"]["value"] or 0.0,
                )
            )
            rows.append(" & ".join(cells) + r" \\")
        tables["reviewer-permutation.tex"] = _table(
            "l" + "cc" * len(perm_sizes) + "c",
            " & ".join(["", *(rf"\multicolumn{{2}}{{c}}{{Pool {s}}}" for s in perm_sizes), ""])
            + r" \\"
            "\n"
            + " & ".join(["Backbone", *(["Real", "Shuffled"] * len(perm_sizes)), "$p$"])
            + r" \\",
            rows,
        )
    weights = sorted(
        {
            float(n.split("_w")[-1].removesuffix("_top_1"))
            for n in metrics
            if n.startswith("dinov2_soft_prior_gps") and n.endswith("_top_1") and "_w" in n
        }
    )
    errors = sorted(
        {
            float(n.split("_gps")[1].split("_")[0])
            for n in metrics
            if n.startswith("dinov2_soft_prior_gps")
        }
    )
    if weights and errors:
        rows = []
        for w in weights:
            cells = [f"{w:g}"] + [
                formatted(
                    "top_1", metrics[f"dinov2_soft_prior_gps{e:g}_w{w:g}_top_1"]["value"] or 0.0
                )
                for e in errors
            ]
            rows.append(" & ".join(cells) + r" \\")
        rows.append(r"\midrule")
        rows.append(
            " & ".join(
                ["Held out"] + [_cell(metrics, f"dinov2_soft_prior_gps{e:g}_top_1") for e in errors]
            )
            + r" \\"
        )
        folds = sorted(
            {
                int(n.split("_fold_")[1].split("_")[0])
                for n in metrics
                if "_soft_prior_gps" in n and "_fold_" in n
            }
        )
        rows.append(
            " & ".join(
                ["Chosen $\\lambda$"]
                + [
                    ", ".join(
                        f"{metrics[f'dinov2_soft_prior_gps{e:g}_fold_{f}_weight']['value']:g}"
                        for f in folds
                    )
                    for e in errors
                ]
            )
            + r" \\"
        )
        tables["reviewer-soft-prior.tex"] = _table(
            "l" + "c" * len(errors),
            "$\\lambda$ & " + " & ".join(f"{e:g}\\,m" for e in errors) + r" \\",
            rows,
        )
    if any(n.startswith("null_") for n in metrics):
        cut_offs = sorted({int(n.rsplit("_r_at_", 1)[1]) for n in metrics if n.startswith("null_")})
        rows = [
            " & ".join(
                [label]
                + [_cell(metrics, f"null_{key}_minus_dinov2_disjoint_r_at_{k}") for k in cut_offs]
            )
            + r" \\"
            for key, label in _NULL_CHECKPOINTS
            if f"null_{key}_minus_dinov2_disjoint_r_at_{cut_offs[0]}" in metrics
        ]
        tables["reviewer-null-bounds.tex"] = _table(
            "l" + "c" * len(cut_offs),
            "Against ViT-B/14 & " + " & ".join(f"R@{k}" for k in cut_offs) + r" \\",
            rows,
        )
    return tables


